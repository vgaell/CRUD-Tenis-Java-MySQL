package DTO;

public class TenisDTO {

    private int tenID;
    private String tenFabricante;
    private String tenModelo;

    public int getTenID() {
        return tenID;
    }

    public void setTenID(int tenID) {
        this.tenID = tenID;
    }

    public String getTenFabricante() {
        return tenFabricante;
    }

    public void setTenFabricante(String tenFabricante) {
        this.tenFabricante = tenFabricante;
    }

    public String getTenModelo() {
        return tenModelo;
    }

    public void setTenModelo(String tenModelo) {
        this.tenModelo = tenModelo;
    }
}